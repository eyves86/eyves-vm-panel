export function translateText(value: string): string {
  if (!shouldTranslateText(value)) return value
  const leading = value.match(/^\s*/)?.[0] || ''
  const trailing = value.match(/\s*$/)?.[0] || ''
  const body = value.trim()
  if (!body) return value
  if (exact[body]) return leading + exact[body] + trailing
  // 数字归一化匹配：把 "队列（并发 2）" 归一为 "队列（并发 {n}）" 再查表，
  // 命中后把原始数字填回。这样"标签 + 数字"型模板也能翻译，不必改写页面代码。
  const numeric = translateWithNumberTemplate(body)
  if (numeric !== '') {
    return leading + numeric + trailing
  }
  // 顺序很重要：先做**贪婪最长匹配**的词典翻译（整词优先），再跑正则替换做兜底。
  // 反过来的话，"历史运行记录"会先被正则把"运行"换成 run，变成"历史run记录"，
  // 之后词典里的复合词条就再也匹配不上（实测英文界面出现过该现象）。
  let translated = greedyReplaceWithDictionary(body)
  for (const [pattern, replacement] of replacements) {
    translated = translated.replace(pattern, replacement)
  }
  translated = cleanupTranslatedText(translated)
  // 只要结果里仍残留中文字符，说明该串没有被完整收录 → 整句保留原文。
  // 逐词替换的自动翻译无法覆盖所有句子，输出 "历史run记录"、"已Cancel" 这类
  // 中英夹生文本比保留可读的中文原句更糟（实测英文界面出现过）。这样处理后：
  //   - 完整收录的标签（导航/按钮/表头）→ 正常英文；
  //   - 未收录的句子 → 保持中文原文，不做半截翻译。
  if (/[\u3400-\u9fff]/.test(translated)) {
    return leading + body + trailing
  }
  return leading + translated + trailing
}

// dictionaryKeysLongestFirst 是翻译词典的键，按长度降序（模块级缓存，避免每次调用重排）。
let dictionaryKeysLongestFirst: string[] | null = null

function dictionaryKeys(): string[] {
  if (!dictionaryKeysLongestFirst) {
    dictionaryKeysLongestFirst = Object.keys(exact).sort((a, b) => b.length - a.length)
  }
  return dictionaryKeysLongestFirst
}

function greedyReplaceWithDictionary(value: string): string {
  const keys = dictionaryKeys()
  if (keys.length === 0 || !/[\u3400-\u9fff]/.test(value)) return value
  let out = ''
  for (let i = 0; i < value.length; ) {
    let matched = false
    for (const key of keys) {
      if (key.length > 0 && value.startsWith(key, i)) {
        out += exact[key]
        i += key.length
        matched = true
        break
      }
    }
    if (!matched) {
      out += value[i]
      i += 1
    }
  }
  return out
}

export function shouldTranslateText(value: string): boolean {
  return /[\u3400-\u9fff]/.test(value) || artifactPatterns.some((pattern) => pattern.test(value))
}

function cleanupTranslatedText(value: string): string {
  return value
    .replace(/虚拟Disk，真实 SMART\/Lifetime\/Power-on数据需在物理宿主机View/g, 'Virtual disk. Real SMART, lifetime, and power-on data must be checked on the physical host.')
    .replace(/Virtual Disk，真实 SMART\/Lifetime\/Power-on数据需在物理Host View/g, 'Virtual disk. Real SMART, lifetime, and power-on data must be checked on the physical host.')
    .replace(/Virtual Disk，真实 SMART\/Lifetime\/Power-on数据需在物理宿主机View/g, 'Virtual disk. Real SMART, lifetime, and power-on data must be checked on the physical host.')
    .replace(/虚拟\s*Disk/g, 'Virtual disk')
    .replace(/宿主机\s*View/g, 'physical host')
    .replace(/Back\s*List/g, 'Back to list')
    .replace(/Container\s*List/g, 'Container List')
    .replace(/Snapshot\s*List/g, 'Snapshot List')
    .replace(/All\s*Type/g, 'All types')
    .replace(/All\s*Status/g, 'All statuses')
    .replace(/All\s*System/g, 'All systems')
    .replace(/AutoStop\s*Off/g, 'Auto-stop off')
    .replace(/AutoStop\s*On/g, 'Auto-stop on')
    .replace(/\s{2,}/g, ' ')
}

// translateWithNumberTemplate 处理"标签 + 数字"型文本。
//
// 例：页面上渲染出「队列（并发 2）」「0 运行 / 0 排队」「共 7 个容器」——这类文本
// 每次数字不同，无法靠整句词条覆盖。做法：把连续数字归一为 {n} 后查词典
// （词典里存 '队列（并发 {n}）' 这样的模板），命中则把原数字依次填回。
// 返回空串表示未命中（调用方继续走常规流程）。
function translateWithNumberTemplate(value: string): string {
  if (!/\d/.test(value)) {
    return ''
  }
  const numbers = value.match(/\d+(?:\.\d+)?/g) || []
  const normalized = value.replace(/\d+(?:\.\d+)?/g, '{n}')
  const template = exact[normalized]
  if (!template) {
    return ''
  }
  let index = 0
  return template.replace(/\{n\}/g, () => numbers[index++] ?? '{n}')
}
